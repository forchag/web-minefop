def seed_biography(apps, schema_editor):
    """Fresh installs get this from seed_data.py's exists-guarded
    seed_minister(), which never runs again once a database has already
    been seeded — so this backfills the biography field (blank until now)
    on an already-seeded database. Only fills it in if it's still empty,
    so it won't clobber a biography an editor has since written."""
    MinisterMessage = apps.get_model("core", "MinisterMessage")
    MinisterMessage.objects.filter(biography_fr="").update(
        biography_fr=MINISTER_BIOGRAPHY_FR, biography_en=MINISTER_BIOGRAPHY_EN
    )


